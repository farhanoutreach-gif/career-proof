// Generates data/onet/level_anchors_<version>.json and supabase/migrations/0005_onet_level_anchors.sql
// from O*NET's level_scale_anchors.csv. Anchor text is copied verbatim; nothing is hand-typed.
//
// Usage: node scripts/import-onet-anchors.mjs <dir-with-onet-csvs> <onet-version>
//   e.g. node scripts/import-onet-anchors.mjs ./onet31 31.0
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const [dir, version] = process.argv.slice(2);
if (!dir || !version) {
  console.error("usage: node scripts/import-onet-anchors.mjs <dir> <onet-version>");
  process.exit(1);
}
const SOURCE_BASE = `https://www.onetcenter.org/dl_files/database/db_${version.replace(".", "_")}_csv`;
const FILE = "level_scale_anchors.csv";
const HEADER = ["Element ID", "Element Name", "Scale ID", "Scale Name", "Anchor Value", "Anchor Description"];

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows;
}
function fail(msg) { throw new Error(msg); }

const buf = fs.readFileSync(path.join(dir, FILE));
const sha256 = crypto.createHash("sha256").update(buf).digest("hex");
const [header, ...rows] = parseCsv(buf.toString("utf8").replace(/^﻿/, ""));
if (JSON.stringify(header) !== JSON.stringify(HEADER)) fail(`${FILE}: unexpected columns ${JSON.stringify(header)}`);

// Only LV (level) anchors for skill elements (2.A basic, 2.B cross-functional).
const anchors = rows
  .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ""])))
  .filter((r) => /^2\.[AB]\.\d+\.[a-z]$/.test(r["Element ID"]))
  .map((r) => {
    if (r["Scale ID"] !== "LV") fail(`${r["Element ID"]}: unexpected scale ${r["Scale ID"]}`);
    const value = Number(r["Anchor Value"]);
    if (!Number.isFinite(value) || value < 0 || value > 7) fail(`${r["Element ID"]}: bad anchor value`);
    if (!r["Anchor Description"]) fail(`${r["Element ID"]}: empty description`);
    return { element_id: r["Element ID"], anchor_value: value, anchor_description: r["Anchor Description"] };
  });
const ids = new Set(anchors.map((a) => a.element_id));
if (ids.size !== 35) fail(`expected anchors for 35 skills, got ${ids.size}`);
const keys = new Set(anchors.map((a) => `${a.element_id}|${a.anchor_value}`));
if (keys.size !== anchors.length) fail("duplicate (element, anchor value) rows");

const out = {
  onet_version: version,
  source_file: { url: `${SOURCE_BASE}/${FILE}`, sha256 },
  anchors,
};
fs.mkdirSync("data/onet", { recursive: true });
fs.writeFileSync(`data/onet/level_anchors_${version}.json`, JSON.stringify(out, null, 2) + "\n");

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sql = `-- Generated by scripts/import-onet-anchors.mjs from data/onet/level_anchors_${version}.json. Do not edit by hand.
-- Source: O*NET ${version} Database level_scale_anchors.csv (CC BY 4.0), ${SOURCE_BASE}/
-- Apply via Supabase Dashboard > SQL Editor.

-- Example tasks O*NET uses to illustrate points on the 0-7 level scale, per skill element.
create table public.onet_level_anchors (
  onet_version text not null references public.onet_sources(version),
  element_id text not null,
  anchor_value int not null check (anchor_value between 0 and 7),
  anchor_description text not null,
  primary key (onet_version, element_id, anchor_value)
);

alter table public.onet_level_anchors enable row level security;
revoke all on public.onet_level_anchors from anon, authenticated;
grant select on public.onet_level_anchors to authenticated;
create policy onet_level_anchors_read on public.onet_level_anchors
  for select to authenticated using (true);

insert into public.onet_level_anchors (onet_version, element_id, anchor_value, anchor_description) values
${anchors.map((a) => `  (${q(version)}, ${q(a.element_id)}, ${a.anchor_value}, ${q(a.anchor_description)})`).join(",\n")};
`;
fs.writeFileSync("supabase/migrations/0005_onet_level_anchors.sql", sql);
console.log(JSON.stringify({ version, anchors: anchors.length, skills: ids.size, sha256 }));
